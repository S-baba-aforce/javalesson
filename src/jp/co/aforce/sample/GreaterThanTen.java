package jp.co.aforce.sample;

/*2 変数 num に整数 12 を代入し、その値が10より大きいかどうかを判定するプログラム*/

public class GreaterThanTen {
	public static void main(String args[]) {
		  
		int num = 12;
		if (num >10) {
			System.out.println(num +"は10より大きい");
		}
			else {
				System.out.println(num + "は10より小さい");
			}
			
	}
}
